USED_COORDINATES = set()


def generate_unique_coordinates(district):
    lat_min, lat_max, lon_min, lon_max = STADTTEILE[district]
    for _ in range(200):
        latitude = round(random.uniform(lat_min, lat_max), 6)
        longitude = round(random.uniform(lon_min, lon_max), 6)
        if (latitude, longitude) not in USED_COORDINATES:
            USED_COORDINATES.add((latitude, longitude))
            return latitude, longitude
    raise RuntimeError(f"Could not generate a unique coordinate for '{district}'.")


def is_outdoor(event_type, venue_name):
    return event_type in OUTDOOR_EVENT_TYPES or venue_name.startswith(OUTDOOR_VENUE_PREFIXES)


def day_weights(event_type, days):
    """Weight for each possible day depending on season and weekday of the event type."""
    month_w = SEASON[event_type]
    weekday_w = WEEKDAY_GROUP[event_type]
    weights = []
    for d in days:
        if event_type == "Weihnachtsmarkt":
            in_window = (d.month == 11 and d.day >= 22) or (d.month == 12 and d.day <= 23)
            weights.append(weekday_w[d.weekday()] if in_window else 0.0)
        else:
            weights.append(month_w[d.month - 1] * weekday_w[d.weekday()])
    return weights if sum(weights) > 0 else [1.0] * len(days)


def escape_sql_value(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, datetime):
        return f"'{value.strftime('%Y-%m-%d %H:%M:%S')}'"
    if hasattr(value, "isoformat"):
        return f"'{value.isoformat()}'"
    return "'" + str(value).replace("'", "''") + "'"


def write_csv(file_name, columns, rows):
    with open(file_name, "w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerow(columns)
        writer.writerows(rows)
    print(f"  -> {file_name} ({len(rows)} rows)")


def write_sql(file_name, table_name, columns, rows):
    """INSERT statements without the identity column (first column)."""
    sql_columns = ", ".join(columns[1:])
    with open(file_name, "a", encoding="utf-8") as file:
        file.write(f"\n-- {table_name} ({len(rows)} rows)\n")
        for row in rows:
            values = ", ".join(escape_sql_value(v) for v in row[1:])
            file.write(f"INSERT INTO cityevents.{table_name} ({sql_columns}) VALUES ({values});\n")


def write_truncate(file_name, table_names):
    tables = ", ".join(f"cityevents.{t}" for t in table_names)
    with open(file_name, "w", encoding="utf-8") as file:
        file.write("-- Empty tables and restart the IDENTITY sequences before loading.\n")
        file.write(f"TRUNCATE TABLE {tables} RESTART IDENTITY CASCADE;\n")


