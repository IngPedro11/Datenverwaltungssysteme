    """config (opcional, lo usa main.py): start_date, end_date, seed, defaults (usar cantidades
    por defecto), csv. Lo que falte en config se pregunta como siempre."""
    config = config or {}
    _ask = (lambda mensaje, valor: valor) if config.get("defaults") else ask_integer

    print("=== Synthetic Data Generator — CityEvents (Dresden) ===\n")
    n_venues = _ask("How many Veranstaltungsorte do you want to generate?", 20)
    n_organizers = _ask("How many Veranstalter do you want to generate?", 15)
    n_events = _ask("How many Veranstaltungen do you want to generate?", 40)
