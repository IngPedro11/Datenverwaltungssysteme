def ask_integer(message, default_value):
    user_input = input(f"{message} [{default_value}]: ").strip()
    if user_input == "":
        return default_value
    try:
        return max(1, int(user_input))
    except ValueError:
        print("  Invalid value. The default value will be used.")
        return default_value


def ask_date(message, default_value):
    """Date as DD.MM.YYYY or YYYY-MM-DD."""
    while True:
        user_input = input(f"{message} [{default_value.strftime('%d.%m.%Y')}]: ").strip()
        if user_input == "":
            return default_value
        for fmt in ("%d.%m.%Y", "%Y-%m-%d"):
            try:
                return datetime.strptime(user_input, fmt).date()
            except ValueError:
                pass
        print("  Invalid date. Use DD.MM.YYYY or YYYY-MM-DD.")


