"""
Synthetic data generator for the CityEvents system (Dresden, Saxony).

Designed for the PostgreSQL `cityevents` schema with columns using
`GENERATED ALWAYS AS IDENTITY`. IDs are generated by PostgreSQL; the script
first empties the tables with `TRUNCATE ... RESTART IDENTITY CASCADE` and then
inserts rows in the order they were created in Python, so the identity values
match the IDs used internally for foreign keys.

NEW
  * Start and end date are selectable; every date falls inside that range.
  * Weather comes from dresden_weather.py (shared with AirSense, BikeShare and
    CityMove: same date = same weather).
      - Outdoor events (festivals, markets, open-air venues ...) are cancelled
        more often when it rains, fewer ticket holders show up, more tickets are
        cancelled and "Wetter" incidents are more frequent.
      - Events follow realistic seasons / weekdays / start times
        (Weihnachtsmarkt only late Nov - 23 Dec, concerts in the evening, ...).
  * Status (geplant / laufend / abgeschlossen) depends on "now": past dates are
    abgeschlossen, future dates geplant.

Run THIS script first: CityMove reads cityevents_veranstaltungstermin.csv and
cityevents_veranstaltungsort.csv to add extra public transport around events.

Standard library only (plus dresden_weather.py in the same folder).
"""

