    n_tickets = _ask("How many Tickets in total do you want to generate?", 1000)

    today = datetime.now().date()
    if "start_date" in config and "end_date" in config:
        start_date, end_date = config["start_date"], config["end_date"]
    else:
        while True:
            start_date = ask_date("Start date", today - timedelta(days=180))
            end_date = ask_date("End date", today)
            if start_date <= end_date:
                break
            print("  The end date must not be before the start date.")

    seed = str(config["seed"]) if "seed" in config else input("Random seed (empty = random): ").strip()
    if seed:
        random.seed(seed)

    print("\nGenerating data...\n")
    (veranstaltungstypen, veranstalter, orte, besucher, veranstaltungen,
     termine, tickets, einlass, stoerungen, termin_outdoor) = generate_data(
        n_venues, n_organizers, n_events, n_dates, n_visitors, n_tickets, start_date, end_date)

    tables = [
        ("Veranstaltungstyp", "veranstaltungstyp", ["id", "bezeichnung"], veranstaltungstypen),
        ("Veranstalter", "veranstalter", ["id", "name", "organisationstyp"], veranstalter),
        ("Veranstaltungsort", "veranstaltungsort",
         ["id", "name", "stadtteil", "adresse", "latitude", "longitude", "kapazitaet"], orte),
        ("Besucher", "besucher", ["id", "kundentyp", "registrierungsdatum"], besucher),
        ("Veranstaltung", "veranstaltung",
         ["id", "name", "id_typ", "id_veranstalter", "beschreibung"], veranstaltungen),
        ("Veranstaltungstermin", "veranstaltungstermin",
         ["id", "id_veranstaltung", "id_veranstaltungsort", "beginn_geplant", "ende_geplant",
          "beginn_tatsaechlich", "ende_tatsaechlich", "status"], termine),
        ("Ticket", "ticket",
         ["id", "id_termin", "id_besucher", "tickettyp", "preis", "kaufzeitpunkt", "status"], tickets),
        ("Einlass", "einlass", ["id", "id_ticket", "einlasszeitpunkt", "einlass_status"], einlass),
        ("Stoerung", "stoerung", ["id", "id_termin", "typ", "beginn", "ende", "beschreibung"],
         stoerungen),
    ]

    print("Writing CSV files:")
    for _, csv_name, columns, rows in tables:
        write_csv(f"cityevents_{csv_name}.csv", columns, rows)

    sql_file = "cityevents_inserts.sql"
    write_truncate(sql_file, [t[0] for t in reversed(tables)])
    print(f"\nWriting SQL script: {sql_file}")
    for table_name, _, columns, rows in tables:
        write_sql(sql_file, table_name, columns, rows)

    print("\nDone! Summary:")
    print(f"  Period:                 {start_date:%d.%m.%Y} – {end_date:%d.%m.%Y}")
    for table_name, _, _, rows in tables:
        print(f"  {table_name:<24}{len(rows)}")
    print(f"  Unique coordinates used: {len(USED_COORDINATES)}")
