def generate_data(n_venues, n_organizers, n_events, n_dates, n_visitors, n_tickets,
                  start_date, end_date):
    now = datetime.now().replace(microsecond=0)
    today = now.date()
    weather.build_weather(end_date)
    all_days = [start_date + timedelta(days=i) for i in range((end_date - start_date).days + 1)]

    veranstaltungstypen = [(i + 1, t) for i, t in enumerate(VERANSTALTUNGSTYPEN)]
    type_name = dict(veranstaltungstypen)

    # --- Veranstalter ---
    veranstalter = [(i, name, org) for i, (name, org) in enumerate(VERANSTALTER_FIXED, start=1)]
    for i in range(len(VERANSTALTER_FIXED) + 1, n_organizers + 1):
        veranstalter.append((i, f"{random.choice(VERANSTALTER_PREFIXES)} "
                                f"{random.choice(STADTTEIL_NAMES)}",
                             random.choice(ORGANISATIONSTYPEN)))

    # --- Veranstaltungsort ---
    orte = []
    for i in range(1, n_venues + 1):
        district = random.choice(STADTTEIL_NAMES)
        latitude, longitude = generate_unique_coordinates(district)
        name = random.choice(VENUE_NAME_TEMPLATES).format(district=district)
        address = f"{random.choice(STREETS)} {random.randint(1, 150)}, {district}"
        capacity = random.choice([80, 150, 300, 500, 800, 1500, 3000, 8000, 20000])
        orte.append((i, name, district, address, latitude, longitude, capacity))

    # --- Besucher: 85 % registered before start, 15 % during the period ---
    anchor = min(start_date, today)
    reg_limit = min(end_date, today)
    besucher = []
    for i in range(1, n_visitors + 1):
        if i == 1 or random.random() < 0.85 or reg_limit < start_date:
            reg_date = anchor - timedelta(days=random.randint(1, 2000))
        else:
            reg_date = start_date + timedelta(days=random.randint(0, (reg_limit - start_date).days))
        besucher.append((i, random.choice(BESUCHER_CUSTOMER_TYPES), reg_date))
    visitors_sorted = sorted(besucher, key=lambda b: b[2])
    reg_dates_sorted = [b[2] for b in visitors_sorted]

    # --- Veranstaltung ---
    adjectives = ["Große", "Traditionelle", "Internationale", "Regionale",
                  "Jährliche", "Besondere", "Offene"]
    veranstaltungen = []
    for i in range(1, n_events + 1):
        type_id, event_type = random.choice(veranstaltungstypen)
        organizer_id, organizer_name, _ = random.choice(veranstalter)
        year = random.randint(start_date.year, end_date.year)
        veranstaltungen.append((i, f"{random.choice(adjectives)} {event_type} {year}",
                                type_id, organizer_id,
                                f"{event_type} organisiert von {organizer_name} in Dresden."))

    # --- Veranstaltungstermin (season / weekday / weather dependent) ---
    termine, termin_outdoor = [], {}
    weights_cache = {}
    for i in range(1, n_dates + 1):
        event = random.choice(veranstaltungen)
        event_type = type_name[event[2]]
        venue = random.choice(orte)
        if event_type not in weights_cache:
            weights_cache[event_type] = day_weights(event_type, all_days)
        day = random.choices(all_days, weights=weights_cache[event_type], k=1)[0]
        hours, durations = EVENT_PROFILE[event_type]
        planned_start = datetime.combine(day, time(random.choice(hours), random.choice([0, 30])))
        planned_end = planned_start + timedelta(hours=random.choice(durations))

        outdoor = is_outdoor(event_type, venue[1])
        rain_mm = weather.day_info(day).rain_mm
        if planned_start > now:
            status = "geplant"
        elif planned_end < now:
            status = "abgeschlossen"
        else:
            status = "laufend"
        p_cancel = 0.04
        if outdoor:
            p_cancel += 0.15 if rain_mm >= 8 else (0.05 if rain_mm > 0 else 0.0)
        if random.random() < p_cancel:
            status = "abgesagt"

        actual_start = actual_end = None
        if status == "abgeschlossen":
            actual_start = planned_start + timedelta(minutes=random.randint(-15, 30))
            actual_end = planned_end + timedelta(minutes=random.randint(-15, 45))
        elif status == "laufend":
            actual_start = min(now, planned_start + timedelta(minutes=random.randint(-10, 10)))

        termin_outdoor[i] = outdoor
        termine.append((i, event[0], venue[0], planned_start, planned_end,
                        actual_start, actual_end, status))

    date_by_id = {t[0]: t for t in termine}

    def weather_of(termin):
        """(Regenmenge des Tages, Temperatur bei Beginn) für einen Termin."""
        return (weather.day_info(termin[3].date()).rain_mm, weather.temperature(termin[3]))

    # --- Ticket ---
    sellable = [t for t in termine if t[7] != "abgesagt"]
    tickets = []
    if sellable:
        raw = [random.random() for _ in sellable]
        total = sum(raw)
        quantities = [max(1, round(n_tickets * w / total)) for w in raw]
        difference, idx = n_tickets - sum(quantities), 0
        while difference != 0:
            pos = idx % len(sellable)
            if difference > 0:
                quantities[pos] += 1
                difference -= 1
            elif quantities[pos] > 1:
                quantities[pos] -= 1
                difference += 1
            idx += 1

        ticket_id = 1
        for termin, quantity in zip(sellable, quantities):
            date_id, planned_start = termin[0], termin[3]
            rain_mm, _ = weather_of(termin)
            outdoor = termin_outdoor[date_id]
            limit_dt = min(planned_start, now)
            k = bisect.bisect_left(reg_dates_sorted, limit_dt.date())
            if not outdoor or rain_mm == 0:
                w_status = TICKET_W_NORMAL
            else:
                w_status = TICKET_W_HEAVY_RAIN if rain_mm >= 8 else TICKET_W_RAIN
            for _ in range(quantity):
                visitor = visitors_sorted[random.randrange(k)] if k > 0 else visitors_sorted[0]
                ticket_type = random.choice(list(TICKET_TYPES))
                price = round(random.uniform(*TICKET_TYPES[ticket_type]), 2)
                purchase = planned_start - timedelta(days=random.uniform(1, 120))
                if purchase > now:
                    purchase = now - timedelta(hours=random.uniform(1, 72))
                reg_dt = datetime.combine(visitor[2], time(0))
                if purchase < reg_dt:
                    purchase = reg_dt + timedelta(hours=random.uniform(1, 48))
                purchase = min(purchase, limit_dt).replace(microsecond=0)
                status = random.choices(TICKET_STATUSES, weights=w_status, k=1)[0]
                tickets.append((ticket_id, date_id, visitor[0], ticket_type, price,
                                purchase, status))
                ticket_id += 1

    # --- Einlass (only paid tickets of events that have started) ---
    einlass, entry_id = [], 1
    for ticket in tickets:
        ticket_id, date_id, _, _, _, _, ticket_status = ticket
        termin = date_by_id[date_id]
        if ticket_status != "bezahlt" or termin[7] not in ("abgeschlossen", "laufend"):
            continue
        show_prob = 0.85
        if termin_outdoor[date_id]:
            rain_mm, temp = weather_of(termin)
            show_prob *= 0.5 if rain_mm >= 8 else (0.7 if rain_mm > 0 else 1.0)
            show_prob *= 0.8 if temp < 0 else 1.0
        if random.random() < show_prob:
            actual_start = termin[5] or termin[3]
            entry_time = actual_start + timedelta(minutes=random.randint(-30, 20))
            einlass.append((entry_id, ticket_id, entry_time, random.choice(EINLASS_STATUSES)))
            entry_id += 1

    # --- Stoerung (more "Wetter" incidents for outdoor events in the rain) ---
    stoerungen, incident_id = [], 1
    for termin in termine:
        date_id, planned_start, planned_end, actual_start, actual_end, status = (
            termin[0], termin[3], termin[4], termin[5], termin[6], termin[7])
        if status not in ("abgeschlossen", "laufend"):
            continue
        rainy_outdoor = termin_outdoor[date_id] and weather_of(termin)[0] > 0
        if random.random() >= (0.35 if rainy_outdoor else 0.15):
            continue
        ref_start = actual_start or planned_start
        ref_end = actual_end or planned_end
        duration_total = max(1, (ref_end - ref_start).total_seconds() / 60)
        type_weights = [1, 6 if rainy_outdoor else 1, 1, 1, 1]
        for _ in range(random.randint(1, 2)):
            incident_type = random.choices(STOERUNG_TYPES, weights=type_weights, k=1)[0]
            incident_start = ref_start + timedelta(minutes=random.uniform(0, duration_total))
            incident_end = incident_start + timedelta(minutes=random.randint(5, 60))
            stoerungen.append((incident_id, date_id, incident_type, incident_start.replace(microsecond=0),
                               incident_end.replace(microsecond=0),
                               f"{incident_type} während der Veranstaltung."))
            incident_id += 1

    return (veranstaltungstypen, veranstalter, orte, besucher, veranstaltungen,
            termine, tickets, einlass, stoerungen, termin_outdoor)


def weather_summary(termine, tickets, einlass, termin_outdoor):
    """Quick check: attendance of outdoor events with / without rain."""
    paid = {}
    for t in tickets:
        if t[6] == "bezahlt":
            paid[t[1]] = paid.get(t[1], 0) + 1
    entered = {}
    ticket_date = {t[0]: t[1] for t in tickets}
    for e in einlass:
        entered[ticket_date[e[1]]] = entered.get(ticket_date[e[1]], 0) + 1
    groups = {"Outdoor, trocken": [0, 0], "Outdoor, Regen": [0, 0], "Indoor": [0, 0]}
    cancelled = {"Outdoor, trocken": [0, 0], "Outdoor, Regen": [0, 0], "Indoor": [0, 0]}
    for t in termine:
        rain = weather.day_info(t[3].date()).rain_mm > 0
        key = "Indoor" if not termin_outdoor[t[0]] else ("Outdoor, Regen" if rain else "Outdoor, trocken")
        cancelled[key][1] += 1
        cancelled[key][0] += t[7] == "abgesagt"
        if t[7] in ("abgeschlossen", "laufend") and paid.get(t[0]):
            groups[key][0] += entered.get(t[0], 0)
            groups[key][1] += paid[t[0]]
    print("\nEffect of the weather (check):")
    for key in groups:
        c, n = cancelled[key]
        a, p = groups[key]
        print(f"  {key:<17} cancelled: {100 * c / n if n else 0:5.1f} %   "
              f"attendance of paid tickets: {100 * a / p if p else 0:5.1f} %")


